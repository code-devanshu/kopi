// Kopi pasteboard spike (issue #4).
//
// A tiny AppKit app with one button per test. Each test touches the general
// pasteboard in exactly one way, so we can see which call (if any) makes macOS
// show the "paste from other apps" alert. Every line goes to the window and to
// ~/Library/Logs/KopiSpike.log.
//
// Clip content is never logged: only lengths, type names, sizes and timings.

import AppKit
import Security

// MARK: - Log

final class Log {
    static let shared = Log()
    let fileURL = FileManager.default.homeDirectoryForCurrentUser
        .appendingPathComponent("Library/Logs/KopiSpike.log")
    var onLine: ((String) -> Void)?
    private let lock = NSLock()
    private let stamp: ISO8601DateFormatter = {
        let f = ISO8601DateFormatter()
        f.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        return f
    }()

    /// Safe from any thread. The file is written straight away, so a later hang
    /// can't lose the line; the window gets it on the main thread.
    func write(_ message: String) {
        lock.lock()
        defer { lock.unlock() }
        let line = "\(stamp.string(from: Date()))  \(message)"
        if let onLine {
            DispatchQueue.main.async { onLine(line) }
        }
        let data = Data((line + "\n").utf8)
        if let handle = try? FileHandle(forWritingTo: fileURL) {
            handle.seekToEndOfFile()
            handle.write(data)
            try? handle.close()
        } else {
            try? data.write(to: fileURL)
        }
    }
}

func log(_ message: String) { Log.shared.write(message) }

// MARK: - Helpers

let pasteboard = NSPasteboard.general

/// Runs `body` and returns its result with the wall time in milliseconds.
/// A call that blocks on a system alert shows up as a long duration.
func timed<T>(_ body: () -> T) -> (T, String) {
    let start = CFAbsoluteTimeGetCurrent()
    let result = body()
    let ms = (CFAbsoluteTimeGetCurrent() - start) * 1000
    return (result, String(format: "%.1f ms", ms))
}

func accessBehaviorDescription() -> String {
    if #available(macOS 15.4, *) {
        switch pasteboard.accessBehavior {
        case .default: return "default"
        case .ask: return "ask"
        case .alwaysAllow: return "alwaysAllow"
        case .alwaysDeny: return "alwaysDeny"
        @unknown default: return "unknown(\(pasteboard.accessBehavior.rawValue))"
        }
    }
    return "n/a (accessBehavior needs macOS 15.4+)"
}

func osBuild() -> String {
    var size = 0
    sysctlbyname("kern.osversion", nil, &size, nil, 0)
    var buffer = [CChar](repeating: 0, count: size)
    sysctlbyname("kern.osversion", &buffer, &size, nil, 0)
    return String(cString: buffer)
}

func signingDescription() -> String {
    var code: SecCode?
    guard SecCodeCopySelf([], &code) == errSecSuccess, let code else { return "unavailable" }
    var staticCode: SecStaticCode?
    guard SecCodeCopyStaticCode(code, [], &staticCode) == errSecSuccess, let staticCode else { return "unavailable" }
    var info: CFDictionary?
    guard SecCodeCopySigningInformation(staticCode, SecCSFlags(rawValue: kSecCSSigningInformation), &info) == errSecSuccess,
          let dict = info as? [String: Any] else { return "unavailable" }
    let identifier = dict[kSecCodeInfoIdentifier as String] as? String ?? "?"
    let cdhash = (dict[kSecCodeInfoUnique as String] as? Data)?.map { String(format: "%02x", $0) }.joined() ?? "?"
    let team = dict[kSecCodeInfoTeamIdentifier as String] as? String ?? "none (ad-hoc)"
    return "identifier=\(identifier) team=\(team) cdhash=\(cdhash)"
}

func frontmostApp() -> String {
    NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "unknown"
}

func describeTypes(_ types: [NSPasteboard.PasteboardType]?) -> String {
    guard let types else { return "nil" }
    if types.isEmpty { return "[] (empty)" }
    return "[" + types.map(\.rawValue).joined(separator: ", ") + "]"
}

/// Markers that mean "don't record this", from nspasteboard.org plus legacy ones.
let privacyMarkers: [String: String] = [
    "org.nspasteboard.ConcealedType": "concealed",
    "org.nspasteboard.TransientType": "transient",
    "org.nspasteboard.AutoGeneratedType": "auto-generated",
    "com.agilebits.onepassword": "concealed (legacy 1Password)",
    "de.petermaurer.TransientPasteboardType": "transient (legacy)",
    "com.typeit4me.clipping": "transient (legacy TypeIt4Me)",
    "Pasteboard generator type": "auto-generated (legacy)",
]

// MARK: - Tests

final class Spike {
    // Pasteboard calls stay on the main thread: on macOS 27.0.1, accessBehavior
    // called from a background queue raises NSInternalInconsistencyException in
    // -[HIRunLoopSemaphore wait:] and the app aborts. The same call on the main
    // thread can block with no time limit, so a watchdog on its own queue logs how
    // long the main thread has been stuck. The window freezes; the log file doesn't.
    private let watchdogQueue = DispatchQueue(label: "in.devanshuverma.kopi.spike.watchdog")
    private var pollTimer: Timer?
    private var pollTicks = 0
    private var lastCount = 0
    private var changesSeen = 0
    var onPollStateChange: ((Bool) -> Void)?

    /// Runs one test on the main thread with a watchdog that logs every 5 s while it blocks.
    func run(_ label: String, _ body: () -> Void) {
        log("[\(label)] started")
        let start = Date()
        let watchdog = DispatchSource.makeTimerSource(queue: watchdogQueue)
        watchdog.schedule(deadline: .now() + 5, repeating: 5)
        watchdog.setEventHandler {
            log("[\(label)] main thread still blocked after \(Int(Date().timeIntervalSince(start))) s")
        }
        watchdog.resume()
        body()
        watchdog.cancel()
        let seconds = Date().timeIntervalSince(start)
        if seconds >= 1 {
            log("[\(label)] main thread free again after \(String(format: "%.1f", seconds)) s")
        }
    }

    func launchReport() {
        let info = Bundle.main.infoDictionary ?? [:]
        log("==================== KopiSpike launched ====================")
        log("macOS \(ProcessInfo.processInfo.operatingSystemVersionString), kern.osversion \(osBuild())")
        log("bundle \(Bundle.main.bundleIdentifier ?? "?") version \(info["CFBundleShortVersionString"] ?? "?") (\(info["CFBundleVersion"] ?? "?")), pid \(ProcessInfo.processInfo.processIdentifier)")
        log("signing: \(signingDescription())")
        let flag = UserDefaults.standard.object(forKey: "EnablePasteboardPrivacyDeveloperPreview")
        log("EnablePasteboardPrivacyDeveloperPreview = \(flag.map { "\($0)" } ?? "not set")")
        log("accessBehavior at launch: \(accessBehaviorDescription())")
        log("log file: \(Log.shared.fileURL.path)")
    }

    func checkAccess() {
        log("[access] accessBehavior = \(accessBehaviorDescription())")
    }

    // Test A: poll changeCount only, every 0.5 s for 60 s. Touches nothing else.
    func startPolling() {
        guard pollTimer == nil else { return }
        pollTicks = 0
        changesSeen = 0
        let (count, ms) = timed { pasteboard.changeCount }
        lastCount = count
        log("[A] start: changeCount=\(count) (\(ms)), accessBehavior=\(accessBehaviorDescription()). Polling every 0.5 s for 60 s.")
        onPollStateChange?(true)
        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.pollTick()
        }
    }

    private func pollTick() {
        pollTicks += 1
        let (count, ms) = timed { pasteboard.changeCount }
        if count != lastCount {
            changesSeen += 1
            log("[A] t=\(String(format: "%.1f", Double(pollTicks) * 0.5)) s changeCount \(lastCount) -> \(count) (\(ms)), frontmost=\(frontmostApp())")
            lastCount = count
        } else if pollTicks % 20 == 0 {
            log("[A] t=\(pollTicks / 2) s still polling, changeCount=\(count)")
        }
        if pollTicks >= 120 {
            pollTimer?.invalidate()
            pollTimer = nil
            log("[A] done: 120 polls, \(changesSeen) change(s) seen, accessBehavior=\(accessBehaviorDescription())")
            onPollStateChange?(false)
        }
    }

    // Test B: read the type list only.
    func readTypes() {
        log("[B] before: changeCount=\(pasteboard.changeCount), accessBehavior=\(accessBehaviorDescription())")
        let (types, ms) = timed { pasteboard.types }
        log("[B] types (\(ms)): \(describeTypes(types))")
        let (items, itemsMs) = timed { pasteboard.pasteboardItems?.count }
        log("[B] pasteboardItems.count (\(itemsMs)): \(items.map(String.init) ?? "nil")")
        log("[B] after: accessBehavior=\(accessBehaviorDescription())")
    }

    // Test C: read the plain-text string. Logs only whether it came back and its length.
    func readString() {
        log("[C] before: changeCount=\(pasteboard.changeCount), accessBehavior=\(accessBehaviorDescription())")
        let (text, ms) = timed { pasteboard.string(forType: .string) }
        if let text {
            let expected = text == "kopi spike test"
            log("[C] string(forType: .string) (\(ms)): \(text.count) characters, matches \"kopi spike test\": \(expected)")
        } else {
            log("[C] string(forType: .string) (\(ms)): nil")
        }
        log("[C] after: accessBehavior=\(accessBehaviorDescription())")
    }

    // Test D: read an image (PNG first, then TIFF). Logs byte count and pixel size.
    func readImage() {
        log("[D] before: changeCount=\(pasteboard.changeCount), accessBehavior=\(accessBehaviorDescription())")
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            let (data, ms) = timed { pasteboard.data(forType: type) }
            guard let data else {
                log("[D] data(forType: \(type.rawValue)) (\(ms)): nil")
                continue
            }
            let size = NSBitmapImageRep(data: data).map { "\($0.pixelsWide)x\($0.pixelsHigh) px" } ?? "not decodable"
            log("[D] data(forType: \(type.rawValue)) (\(ms)): \(data.count) bytes, \(size)")
            break
        }
        log("[D] after: accessBehavior=\(accessBehaviorDescription())")
    }

    // Test E: decide from the type list alone. Content is read only when no privacy marker is present.
    func privacyFilter() {
        log("[E] before: changeCount=\(pasteboard.changeCount), accessBehavior=\(accessBehaviorDescription())")
        let (types, ms) = timed { pasteboard.types }
        log("[E] types (\(ms)): \(describeTypes(types))")
        let hits = (types ?? []).compactMap { privacyMarkers[$0.rawValue] }
        if !hits.isEmpty {
            log("[E] SKIPPED without reading content: \(hits.joined(separator: ", "))")
        } else {
            let (text, readMs) = timed { pasteboard.string(forType: .string) }
            log("[E] no privacy marker, would capture: string \(text.map { "\($0.count) characters" } ?? "nil") (\(readMs))")
        }
        log("[E] after: accessBehavior=\(accessBehaviorDescription())")
    }

    // Helpers for Test E: put marked samples on the pasteboard. Writing never needs permission.
    func writeSample(marker: String, label: String) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString("kopi spike \(label) sample", forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
        pasteboard.writeObjects([item])
        log("[E] wrote a \(label) sample (string + \(marker)), changeCount=\(pasteboard.changeCount)")
    }
}

// MARK: - UI

final class AppDelegate: NSObject, NSApplicationDelegate {
    private var window: NSWindow!
    private let textView = NSTextView()
    private let spike = Spike()
    private var pollButton: NSButton!

    func applicationDidFinishLaunching(_ notification: Notification) {
        buildWindow()
        Log.shared.onLine = { [weak self] line in self?.append(line) }
        spike.onPollStateChange = { [weak self] running in
            self?.pollButton.isEnabled = !running
            self?.pollButton.title = running ? "A: polling…" : "A: Poll changeCount (60 s)"
        }
        DispatchQueue.main.async { self.spike.run("launch") { self.spike.launchReport() } }
        NSApp.activate(ignoringOtherApps: true)
    }

    func applicationShouldTerminateAfterLastWindowClosed(_ sender: NSApplication) -> Bool { true }

    private func button(_ title: String, _ action: Selector) -> NSButton {
        let b = NSButton(title: title, target: self, action: action)
        b.bezelStyle = .rounded
        return b
    }

    private func buildWindow() {
        window = NSWindow(
            contentRect: NSRect(x: 0, y: 0, width: 900, height: 600),
            styleMask: [.titled, .closable, .miniaturizable, .resizable],
            backing: .buffered, defer: false)
        window.title = "Kopi pasteboard spike"
        window.center()

        pollButton = button("A: Poll changeCount (60 s)", #selector(testA))
        let tests = NSStackView(views: [
            pollButton,
            button("B: Read types", #selector(testB)),
            button("C: Read string", #selector(testC)),
            button("D: Read image", #selector(testD)),
            button("E: Privacy filter", #selector(testE)),
        ])
        let helpers = NSStackView(views: [
            button("Check accessBehavior", #selector(checkAccess)),
            button("Copy concealed sample", #selector(copyConcealed)),
            button("Copy transient sample", #selector(copyTransient)),
            button("Clear window", #selector(clearWindow)),
        ])
        for row in [tests, helpers] {
            row.orientation = .horizontal
            row.spacing = 8
        }

        textView.isEditable = false
        textView.font = .monospacedSystemFont(ofSize: 11, weight: .regular)
        textView.autoresizingMask = [.width]
        textView.textContainerInset = NSSize(width: 6, height: 6)
        let scroll = NSScrollView()
        scroll.documentView = textView
        scroll.hasVerticalScroller = true
        scroll.borderType = .bezelBorder

        let content = NSStackView(views: [tests, helpers, scroll])
        content.orientation = .vertical
        content.alignment = .leading
        content.spacing = 10
        content.edgeInsets = NSEdgeInsets(top: 12, left: 12, bottom: 12, right: 12)
        content.translatesAutoresizingMaskIntoConstraints = false
        window.contentView = NSView()
        window.contentView!.addSubview(content)
        NSLayoutConstraint.activate([
            content.leadingAnchor.constraint(equalTo: window.contentView!.leadingAnchor),
            content.trailingAnchor.constraint(equalTo: window.contentView!.trailingAnchor),
            content.topAnchor.constraint(equalTo: window.contentView!.topAnchor),
            content.bottomAnchor.constraint(equalTo: window.contentView!.bottomAnchor),
            scroll.widthAnchor.constraint(equalTo: content.widthAnchor, constant: -24),
        ])
        window.makeKeyAndOrderFront(nil)
    }

    private func append(_ line: String) {
        let attributed = NSAttributedString(string: line + "\n", attributes: [
            .font: NSFont.monospacedSystemFont(ofSize: 11, weight: .regular),
            .foregroundColor: NSColor.textColor,
        ])
        textView.textStorage?.append(attributed)
        textView.scrollToEndOfDocument(nil)
    }

    @objc private func testA() { spike.startPolling() }
    @objc private func testB() { spike.run("B") { self.spike.readTypes() } }
    @objc private func testC() { spike.run("C") { self.spike.readString() } }
    @objc private func testD() { spike.run("D") { self.spike.readImage() } }
    @objc private func testE() { spike.run("E") { self.spike.privacyFilter() } }
    @objc private func checkAccess() { spike.run("access") { self.spike.checkAccess() } }
    @objc private func copyConcealed() { spike.run("E") { self.spike.writeSample(marker: "org.nspasteboard.ConcealedType", label: "concealed") } }
    @objc private func copyTransient() { spike.run("E") { self.spike.writeSample(marker: "org.nspasteboard.TransientType", label: "transient") } }
    @objc private func clearWindow() { textView.string = "" }
}

let app = NSApplication.shared
let delegate = AppDelegate()
app.delegate = delegate
app.setActivationPolicy(.regular)
app.run()
